import {
  ApplicationHierarchyNode,
  ApplicationHierarchyResult,
  ArgoApplication,
} from '../models/trace';
import {getApplication, listApplications} from './application-service';

const TRACKING_ANNOTATION = 'argocd.argoproj.io/tracking-id';
const INSTANCE_LABELS = [
  'argocd.argoproj.io/instance',
  'app.kubernetes.io/instance',
];
const MAX_DEPTH = 8;

type DirectOwner =
  | {kind: 'Application'; name: string; namespace?: string}
  | {kind: 'ApplicationSet'; name: string; namespace?: string};

function nonEmpty(value?: string): string | undefined {
  const normalized = value?.trim();
  return normalized || undefined;
}

/**
 * Argo CD tracking annotations use this shape:
 *
 *   <application-name>:<group>/<kind>:<namespace>/<resource-name>
 *
 * The first segment identifies the Application that manages the resource.
 */
function applicationNameFromTrackingId(value?: string): string | undefined {
  const trackingId = nonEmpty(value);
  if (!trackingId) return undefined;

  const separator = trackingId.indexOf(':');
  if (separator <= 0) return undefined;
  return nonEmpty(trackingId.slice(0, separator));
}

function directOwnerOf(app: ArgoApplication): DirectOwner | undefined {
  const namespace = app.metadata?.namespace;

  // Applications generated by ApplicationSet have a real Kubernetes ownerRef.
  const applicationSet = app.metadata?.ownerReferences?.find(
    owner => owner.kind === 'ApplicationSet' && owner.name
  );
  if (applicationSet?.name) {
    return {
      kind: 'ApplicationSet',
      name: applicationSet.name,
      namespace,
    };
  }

  // Prefer the Trace annotation, while keeping the old Navigator key as
  // a compatibility fallback for existing installations.
  const explicitParent = nonEmpty(
    app.metadata?.annotations?.['trace.argocd.io/parent-application'] ||
      app.metadata?.annotations?.['navigator.argocd.io/parent-application']
  );
  if (explicitParent && explicitParent !== app.metadata?.name) {
    return {kind: 'Application', name: explicitParent, namespace};
  }

  // App-of-Apps does not normally create an ownerReference to the parent
  // Application. The parent is recorded through Argo CD resource tracking.
  const trackedParent = applicationNameFromTrackingId(
    app.metadata?.annotations?.[TRACKING_ANNOTATION]
  );
  if (trackedParent && trackedParent !== app.metadata?.name) {
    return {kind: 'Application', name: trackedParent, namespace};
  }

  // Label fallback supports label-only resource tracking and custom setups.
  for (const key of INSTANCE_LABELS) {
    const value = nonEmpty(app.metadata?.labels?.[key]);
    if (value && value !== app.metadata?.name) {
      return {kind: 'Application', name: value, namespace};
    }
  }

  return undefined;
}

function routePrefix(segment: 'applications' | 'applicationsets'): URL {
  return new URL(`${segment}/`, document.baseURI);
}

export function applicationDetailsLink(
  name: string,
  namespace?: string
): string {
  const base = routePrefix('applications');
  const appNamespace = namespace || 'argocd';
  return new URL(
    `${encodeURIComponent(appNamespace)}/${encodeURIComponent(name)}`,
    base
  ).toString();
}

/**
 * Argo CD 3.2 does not expose a standalone ApplicationSet details route.
 * ApplicationSets managed by an Application are, however, normal nodes in
 * that parent Application's resource tree. Deep-link to that node so clicking
 * the ApplicationSet in Trace opens Argo CD's native resource details panel.
 */
function applicationSetResourceLink(
  parent: ArgoApplication,
  name: string,
  namespace?: string
): string | undefined {
  const parentName = nonEmpty(parent.metadata?.name);
  if (!parentName) return undefined;

  const appSetNamespace = namespace || parent.metadata?.namespace || 'argocd';
  const url = new URL(
    applicationDetailsLink(parentName, parent.metadata?.namespace)
  );

  const nodeKey = [
    'argoproj.io',
    'ApplicationSet',
    appSetNamespace,
    name,
  ].join('/');

  url.searchParams.set('node', nodeKey);
  return url.toString();
}

function applicationNode(
  app: ArgoApplication,
  current = false
): ApplicationHierarchyNode | undefined {
  const name = nonEmpty(app.metadata?.name);
  if (!name) return undefined;

  return {
    kind: 'Application',
    name,
    namespace: app.metadata?.namespace,
    current,
    href: current
      ? undefined
      : applicationDetailsLink(name, app.metadata?.namespace),
  };
}

function resourceMatchesApplicationSet(
  app: ArgoApplication,
  name: string,
  namespace?: string
): boolean {
  return Boolean(
    app.status?.resources?.some(resource => {
      if (resource.kind !== 'ApplicationSet' || resource.name !== name) {
        return false;
      }

      const group = resource.group || 'argoproj.io';
      if (group !== 'argoproj.io') return false;

      // Some Argo CD responses omit namespace for namespaced resources.
      return !namespace || !resource.namespace || resource.namespace === namespace;
    })
  );
}

async function findApplicationManagingApplicationSet(
  name: string,
  namespace: string | undefined,
  signal?: AbortSignal
): Promise<ArgoApplication | undefined> {
  const applications = await listApplications(signal);
  return applications.find(app =>
    resourceMatchesApplicationSet(app, name, namespace)
  );
}

function keyFor(node: Pick<ApplicationHierarchyNode, 'kind' | 'name' | 'namespace'>): string {
  return `${node.kind}:${node.namespace || 'argocd'}:${node.name}`;
}

/**
 * Builds the ancestry from the current Application up to its root.
 *
 * Supported chains:
 *   Application -> Application
 *   Application -> ApplicationSet -> Application
 *   nested App-of-Apps chains
 */
export async function resolveApplicationHierarchy(
  app: ArgoApplication,
  signal?: AbortSignal
): Promise<ApplicationHierarchyResult> {
  const currentNode = applicationNode(app, true);
  if (!currentNode) {
    return {nodes: [], partial: true, reason: 'Application name is unavailable.'};
  }

  const currentToRoot: ApplicationHierarchyNode[] = [currentNode];
  const visited = new Set<string>([keyFor(currentNode)]);
  let cursor = app;
  let partial = false;
  let reason: string | undefined;

  for (let depth = 0; depth < MAX_DEPTH; depth += 1) {
    const owner = directOwnerOf(cursor);
    if (!owner) break;

    if (owner.kind === 'ApplicationSet') {
      const appSetNode: ApplicationHierarchyNode = {
        kind: 'ApplicationSet',
        name: owner.name,
        namespace: owner.namespace,
      };
      const appSetKey = keyFor(appSetNode);
      if (visited.has(appSetKey)) break;
      visited.add(appSetKey);
      currentToRoot.push(appSetNode);

      // App-of-ApplicationSets: locate the Application whose managed resources
      // include this ApplicationSet. This only runs for an AppSet-owned child.
      try {
        const parentApp = await findApplicationManagingApplicationSet(
          owner.name,
          owner.namespace,
          signal
        );
        if (!parentApp) break;

        // Argo CD 3.2 has no standalone /applicationsets details page.
        // Make the ApplicationSet node clickable by opening the resource
        // details drawer inside the Application that manages it.
        appSetNode.href = applicationSetResourceLink(
          parentApp,
          owner.name,
          owner.namespace
        );

        const parentNode = applicationNode(parentApp);
        if (!parentNode) break;
        const parentKey = keyFor(parentNode);
        if (visited.has(parentKey)) break;
        visited.add(parentKey);
        currentToRoot.push(parentNode);
        cursor = parentApp;
        continue;
      } catch (error) {
        if ((error as {name?: string})?.name === 'AbortError') throw error;
        partial = true;
        reason = 'The ApplicationSet parent could not be resolved.';
        break;
      }
    }

    try {
      const parentApp = await getApplication(
        owner.name,
        owner.namespace,
        signal
      );
      const parentNode = applicationNode(parentApp);
      if (!parentNode) break;

      const parentKey = keyFor(parentNode);
      if (visited.has(parentKey)) break;
      visited.add(parentKey);
      currentToRoot.push(parentNode);
      cursor = parentApp;
    } catch (error) {
      if ((error as {name?: string})?.name === 'AbortError') throw error;
      partial = true;
      reason = `The parent Application “${owner.name}” could not be loaded.`;
      break;
    }
  }

  if (currentToRoot.length >= MAX_DEPTH + 1) {
    partial = true;
    reason = `Hierarchy was limited to ${MAX_DEPTH} parent levels.`;
  }

  return {
    nodes: currentToRoot.reverse(),
    partial,
    reason,
  };
}
